#!/usr/bin/env python3
"""Select the RAM implementation: design decision D1 (docs/spec/07-memory-subsystem.md).

    scripts/select-memory.py macro_512x32          # 1 x RM_IHPSG13_1P_512x32 (default)
    scripts/select-memory.py macro_2x512x16        # 2 x RM_IHPSG13_1P_512x16
    scripts/select-memory.py flops --words 256     # a flip-flop array of N words
    scripts/select-memory.py --show                # what is selected now

It rewrites every place that depends on the choice, so they cannot disagree:
  src/mem/mem_config.svh   RV32U_MEM_OPTION, RV32U_RAM_WORDS (RTL, sw/Makefile, the tests)
  src/config.json          LibreLane config: the SRAM macros, their placement and power
  info.yaml                source_files (the RAM backend, the macro black boxes) and tiles
  src/rv32u.core           the RAM fileset FuseSoC builds (the line marked MEM_OPTION)
Record the choice and your reasons in DESIGN.md (D1).
"""

from __future__ import annotations

import argparse
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

OPTIONS = {
    # 6x2 (~405,000 um^2): the macro (~80,000 / 2 x ~45,000 um^2) plus a ~115,000 um^2
    # core at 60% density, measured with Yosys on the IHP sg13g2 cells (docs/spec/07)
    "macro_512x32": {"words": 512, "file": "mem/ram_macro_512x32.sv", "macro": True,
                     "tiles": "6x2"},
    "macro_2x512x16": {"words": 512, "file": "mem/ram_macro_2x512x16.sv", "macro": True,
                       "tiles": "6x2"},
    "flops": {"words": None, "file": "mem/ram_flops.sv", "macro": False, "tiles": None},
}

# Tiny Tapeout IHP tile sizes, and the area of one tile in gate equivalents
# (202.08 x 154.98 um / 7.2576 um^2 per sg13g2_nand2_1).
TILES = ["1x1", "1x2", "2x2", "3x2", "4x2", "6x2", "8x2", "3x4", "4x4", "5x4", "6x4", "8x4"]
GE_PER_TILE = 4315
CORE_GE = 16_000      # an RV32u core (Yosys, sg13g2 cells): ~80% is the 31 x 32 register file
DENSITY = 0.6         # usable fraction of a tile after placement and routing

SOURCES_HEAD = ["rv32u_pkg.sv", "core/rv32u_regfile.sv",
                "core/rv32u_alu.sv", "core/rv32u_immgen.sv", "core/rv32u_control.sv",
                "core/rv32u_datapath.sv", "core/rv32u_core.sv", "mem/rv32u_mem.sv"]
SOURCES_TAIL = ["io/rv32u_io.sv", "io/rv32u_loader.sv", "rv32u_soc.sv", "tt_um_sharc_rv32u.sv"]


def tiles_for(ge: float) -> str | None:
    """The smallest tile size that fits `ge`, or None if not even 8x4 does."""
    for t in sorted(TILES, key=lambda t: math.prod(map(int, t.split("x")))):
        if math.prod(map(int, t.split("x"))) * GE_PER_TILE * DENSITY >= ge:
            return t
    return None


def flops_ge(words: int) -> float:
    bits = words * 32
    return bits * 7.25 + (words - 1) * 32 * 2.5  # storage + the read multiplexer


def current() -> tuple[str, int]:
    text = (ROOT / "src/mem/mem_config.svh").read_text()
    opt = re.search(r'`define RV32U_MEM_OPTION "(\w+)"', text)
    words = re.search(r"`define RV32U_RAM_WORDS (\d+)", text)
    return (opt.group(1) if opt else "?", int(words.group(1)) if words else 0)


def write_mem_config(option: str, words: int) -> None:
    (ROOT / "src/mem/mem_config.svh").write_text(
        "// Generated by scripts/select-memory.py: do not edit by hand.\n"
        f"// Memory option (design decision D1): {option}\n"
        "`ifndef RV32U_MEM_CONFIG_SVH\n`define RV32U_MEM_CONFIG_SVH\n"
        f'`define RV32U_MEM_OPTION "{option}"\n'
        f"`define RV32U_RAM_WORDS {words}\n"
        "`endif\n")


def write_info_yaml(option: str, tiles: str) -> None:
    path = ROOT / "info.yaml"
    text = path.read_text()
    srcs = SOURCES_HEAD + [OPTIONS[option]["file"]] + SOURCES_TAIL
    if OPTIONS[option]["macro"]:
        srcs.append("sram_bb.sv")
    block = "  source_files:\n" + "".join(f'    - "{s}"\n' for s in srcs)
    text, n = re.subn(r"  source_files:\n(?:    - .*\n)+", block, text)
    if n != 1:
        raise SystemExit("info.yaml: could not find the source_files list")
    text, n = re.subn(r'(\n  tiles: )"[0-9x]+"', rf'\1"{tiles}"', text)
    if n != 1:
        raise SystemExit("info.yaml: could not find tiles")
    path.write_text(text)


def write_core(option: str) -> None:
    path = ROOT / "src/rv32u.core"
    text, n = re.subn(r"      - mem_\w+  # MEM_OPTION", f"      - mem_{option}  # MEM_OPTION",
                      path.read_text())
    if n != 1:
        raise SystemExit("src/rv32u.core: could not find the MEM_OPTION line")
    path.write_text(text)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("option", nargs="?", choices=sorted(OPTIONS))
    ap.add_argument("--words", type=int, default=256,
                    help="RAM words for the flops option (a power of two; default 256)")
    ap.add_argument("--show", action="store_true", help="print the current selection")
    a = ap.parse_args()
    if a.show or a.option is None:
        opt, words = current()
        print(f"memory option: {opt}, {words} words ({words * 4} bytes)")
        return 0
    opt = OPTIONS[a.option]
    words = opt["words"] or a.words
    if words & (words - 1) or not 16 <= words <= 512:
        print("--words must be a power of two from 16 to 512", file=sys.stderr)
        return 2
    if opt["macro"]:
        tiles, ram_ge = opt["tiles"], 0.0
    else:
        ram_ge = flops_ge(words)
        fit = tiles_for(CORE_GE + ram_ge)
        if fit is None:
            print(f"warning: ~{(CORE_GE + ram_ge) / 1000:.0f}k GE does not fit even 8x4 tiles "
                  f"(~{32 * GE_PER_TILE * DENSITY / 1000:.0f}k GE usable); use fewer --words "
                  "or a macro option", file=sys.stderr)
        tiles = fit or "8x4"
    write_mem_config(a.option, words)
    (ROOT / "src/config.json").write_text((ROOT / f"src/config/{a.option}.json").read_text())
    write_info_yaml(a.option, tiles)
    write_core(a.option)
    print(f"memory option: {a.option}, {words} words ({words * 4} bytes), tiles {tiles}")
    if ram_ge:
        print(f"  estimate: RAM ~{ram_ge / 1000:.0f}k GE + core ~{CORE_GE // 1000}k GE at "
              f"{DENSITY:.0%} density -> {tiles} (a rough guide: check the GDS action's "
              "utilisation report)")
    print("  updated src/mem/mem_config.svh, src/config.json, info.yaml, src/rv32u.core")
    print("  next: make -C sw clean && make test; record the choice in DESIGN.md (D1)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
